"""Generate Athena DDL for the curated tables from storage/schema.py.

Output: sql/curated/01_create_curated_tables.sql
Run after changing schema.py:  python storage/generate_ddl.py [--bucket NAME]

Partitioned tables use Athena partition projection, so new source_year folders
are visible without MSCK REPAIR TABLE / ALTER TABLE ADD PARTITION.
"""

import argparse
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from schema import BUCKET, DATABASE, ROOT, S3_PREFIX, TABLES, village_columns  # noqa: E402

# year range covered by projection; widen when a new year of data arrives
PROJECTION_RANGE = {"fact_flood_report": "2566,2567", "fact_disaster_damage": "2563,2567"}


def columns_for(name, spec):
    if spec["columns"] is not None:
        return spec["columns"]
    header = pd.read_csv(spec["source"], nrows=0, encoding="utf-8-sig").columns
    return village_columns(header)


def ddl(name, spec, bucket):
    cols = columns_for(name, spec)
    width = max(len(c) for c, _ in cols)
    body = ",\n".join(f"  `{c}`{' ' * (width - len(c))} {t}" for c, t in cols)
    loc = f"s3://{bucket}/{S3_PREFIX}{name}/"
    lines = [f"-- {name}: {spec['grain']}",
             f"-- primary key: {', '.join(spec['primary_key'])}",
             f"DROP TABLE IF EXISTS {DATABASE}.{name};",
             f"CREATE EXTERNAL TABLE {DATABASE}.{name} (\n{body}\n)"]
    part = spec["partition"]
    if part:
        lines.append(f"PARTITIONED BY (`{part[0]}` {part[1]})")
    lines += ["STORED AS PARQUET", f"LOCATION '{loc}'"]
    props = ["'parquet.compression'='SNAPPY'"]
    if part:
        props += ["'projection.enabled'='true'",
                  f"'projection.{part[0]}.type'='integer'",
                  f"'projection.{part[0]}.range'='{PROJECTION_RANGE[name]}'",
                  f"'storage.location.template'='{loc}{part[0]}=${{{part[0]}}}/'"]
    lines.append("TBLPROPERTIES (\n  " + ",\n  ".join(props) + "\n);")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bucket", default=BUCKET)
    args = ap.parse_args()

    parts = [
        "-- AUTO-GENERATED by storage/generate_ddl.py from storage/schema.py. Do not edit by hand.",
        "-- Curated zone (Person 4): typed Parquet on S3, registered in the Glue Data Catalog via Athena.",
        f"-- Files: s3://{args.bucket}/{S3_PREFIX}<table>/[source_year=YYYY/]part-0.parquet",
        "-- Run each statement in the Athena query editor (one statement per run),",
        "-- or all at once with: python storage/run_athena.py --sql sql/curated/01_create_curated_tables.sql",
        "",
        f"CREATE DATABASE IF NOT EXISTS {DATABASE};",
    ]
    for name, spec in TABLES.items():
        parts += ["", ddl(name, spec, args.bucket)]
    out = ROOT / "sql" / "curated" / "01_create_curated_tables.sql"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
